function buildSeries(
  catalogItemId: string,
  supplierId: string,
  prices: Cents[],
): PricePoint[] {
  const months = [
    "2026-02-15",
    "2026-03-15",
    "2026-04-15",
    "2026-05-15",
    "2026-06-15",
    "2026-07-15",
    "2026-08-10",
  ];
  return prices.map((unitPriceCents, index) => ({
    catalogItemId,
    supplierId,
    date: months[index],
    unitPriceCents,
  }));
}

