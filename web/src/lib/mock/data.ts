interface LineOptions {
  articleNo?: string | null;
  totalCents?: Cents;
  isPfand?: boolean;
  confidence?: number;
  catalogItemId?: string | null;
}

function line(
  id: string,
  rawDescription: string,
  quantity: number,
  unit: string,
  unitPriceCents: Cents,
  vatRate: VatRate,
  options: LineOptions = {},
): DocumentLine {
  return {
    id,
    rawDescription,
    articleNo: options.articleNo ?? null,
    quantity,
    unit,
    unitPriceCents,
    totalCents: options.totalCents ?? Math.round(quantity * unitPriceCents),
    vatRate,
    isPfand: options.isPfand ?? false,
    confidence: options.confidence ?? 0.97,
    catalogItemId: options.catalogItemId ?? null,
  };
}

